const T = ({ children, style, ...props }) => {
  const { language } = useLanguage();
  
  // If children is not a string, just render it
  if (typeof children !== 'string') {
    return <Text style={style} {...props}>{children}</Text>;
  }
  
  // If Urdu is selected and translation exists, show Urdu
  let displayText = children;
  if (language === 'ur' && autoTranslations[children]) {
    displayText = autoTranslations[children];
  }
  
  return <Text style={style} {...props}>{displayText}</Text>;
};

export default T;

